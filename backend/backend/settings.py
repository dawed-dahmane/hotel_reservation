def _require_env(name):
    """Return a required environment variable or refuse to start."""
    value = os.environ.get(name)
    if not value:
        raise ImproperlyConfigured(
            f"{name} is not set. Define it in the environment or in backend/.env "
            "(see backend/.env.example). Generate one with: "
            "python -c \"from django.core.management.utils import get_random_secret_key as g; print(g())\""
        )
    return value


def _env_flag(name, default=False):
    """Read a boolean environment variable without silent truthiness bugs."""
    raw = os.getenv(name)
    if raw is None or raw.strip() == '':
        return default
    return raw.strip().lower() in ('1', 'true', 'yes', 'on')


def _env_list(name):
    """Read a comma-separated environment variable as a list."""
    return [item.strip() for item in os.getenv(name, '').split(',') if item.strip()]


